const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => {
    return localStorage.getItem('agrobloom_lang') || 'en';
  });

  const changeLanguage = (lang) => {
    if (['en', 'kn', 'hi'].includes(lang)) {
      setLanguage(lang);
      localStorage.setItem('agrobloom_lang', lang);
    }
  };

  const t = (key) => {
    return translations[language]?.[key] || translations.en[key] || key;
  };

  const getLocalizedDisease = (classKeyOrName) => {
    if (!classKeyOrName) return '';
    if (language === 'en') {
      return classKeyOrName.replace(/___/g, ' - ').replace(/_/g, ' ');
    }
    const localized = diseaseDictionary[language]?.[classKeyOrName];
    if (localized) return localized;
    return classKeyOrName.replace(/___/g, ' - ').replace(/_/g, ' ');
  };

  return (
    <LanguageContext.Provider value={{ language, changeLanguage, t, getLocalizedDisease, translations: translations[language] }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
